#!/usr/bin/env python3
"""UserPromptSubmit hook - reminds the orchestrator that runs wait for the User (task-0153).

task-0128 sat at plan approval for a day: the orchestrator deferred the card and
forgot, and the Stop hook treats a run parked at a checkpoint as idle. This hook
puts one line per waiting run, across every lane, in front of the model on every
prompt while any run waits, and says nothing otherwise.

Delivery is the hookSpecificOutput envelope with additionalContext (measured on
Claude Code 2.1.307: it reaches the model; the payload carries no agent_id and a
dispatched subagent does not fire this event, so the hook is main-thread only
without a guard). The text states that it is a harness reminder because a model
that sees an unexplained line in hook context may decline to act on it.

Output is ASCII (stdout is cp1252 on Windows hosts), byte-stable for the same
state, at most MAX_RUNS runs and MAX_BYTES bytes. Which runs wait comes from
waiting.py, shared with the Stop hook and the status line.

Silent in a supervisor session (AGENTRY_UNATTENDED): nobody is there to answer a card.

Fail-open (NFR-4): any failure, SystemExit included (`paths` exits 2 when
CLAUDE_PROJECT_DIR is unset, and exit 2 on UserPromptSubmit BLOCKS the prompt), is one
`[needs-you-reminder] <ExcType>: <msg>` line on stderr and exit 0; a prompt is never
blocked by a reminder. `waiting` is therefore imported inside the guarded code, not
at module level.

stdin is read as raw bytes and never decoded: the payload is not needed for the
output, and the locale codec (cp1252 on Windows) raises on UTF-8 Cyrillic prompts,
which would make the reminder silent for exactly those prompts.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "pipeline"))

# Keep this name equal to pretool_gate.UNATTENDED_ENV (pinned by a test); a literal here keeps
# the module free of the heavy pretool_gate import.
UNATTENDED_ENV = "AGENTRY_UNATTENDED"
MAX_RUNS = 5
MAX_BYTES = 1500
HEADER = ("Harness pipeline reminder (generated by the agentry UserPromptSubmit hook, not typed by the "
          "User): {n} run(s) wait for the User. Raise each one as an AskUserQuestion card in this "
          "turn - the situation in two lines, the options with their trade-off, one recommendation - "
          "before any other work. Do not leave it in plain text. If the User's message in this turn already "
          "answers the checkpoint, act on that answer; no extra card is needed.")


def render(runs: list[dict]) -> str:
    """The reminder text, or '' when no run waits."""
    if not runs:
        return ""
    import waiting

    lines = [HEADER.format(n=len(runs))]
    for run in runs[:MAX_RUNS]:
        label = waiting.LABEL.get(run["kind"], run["kind"])
        lines.append(f"- {run['task']} | lane {run['lane']} | {label} | waiting since {run['since']}")
    if len(runs) > MAX_RUNS:
        lines.append(f"+{len(runs) - MAX_RUNS} more")
    text = "\n".join(lines).encode("ascii", "replace").decode("ascii")
    if len(text) > MAX_BYTES:
        text = text[:MAX_BYTES - 3] + "..."
    return text


def drain_stdin() -> None:
    """Consume the payload without decoding it (see the module docstring)."""
    try:
        sys.stdin.buffer.read()
    except Exception:
        pass  # a closed or missing stdin changes nothing about the output


def main() -> int:
    if os.environ.get(UNATTENDED_ENV):
        return 0
    drain_stdin()
    try:
        import waiting

        text = render(waiting.waiting_runs())
        if text:
            print(json.dumps({"hookSpecificOutput": {"hookEventName": "UserPromptSubmit",
                                                     "additionalContext": text}}))
    except (Exception, SystemExit) as exc:
        sys.stderr.write(f"[needs-you-reminder] {type(exc).__name__}: {exc}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
